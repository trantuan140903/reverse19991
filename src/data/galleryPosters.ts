export function getGalleryPosterForVersion(version?: string): GalleryPoster {
  if (!version) return GALLERY_POSTERS[0];
  const v = String(version).replace(/^v/i, "").trim();
  
  // Exact version match (EN first)
  const match = GALLERY_POSTERS.find(p => p.version === v && p.lang === "EN") ||
                GALLERY_POSTERS.find(p => p.version === v);
  if (match) return match;

  // Prefix match (e.g. 1.4.x -> 1.4)
  const prefixMatch = GALLERY_POSTERS.find(p => v.startsWith(p.version));
  if (prefixMatch) return prefixMatch;

  return GALLERY_POSTERS[0];
}
